// Writes the brand file's values into the native projects, or with --check compares them.
//   ios/App/Brand.xcconfig       BRAND_NAME / BRAND_APP_ID / BRAND_SCHEME (Info.plist and the target
//                                read them)
//   android/brand.properties     applicationId and scheme (app/build.gradle reads them)
//   brand-assets.sha256          hash of the brand's source images and colours
//   icon and splash sets         rendered by @capacitor/assets into the iOS and Android projects
// --check writes nothing and exits 1 on drift. Run: pnpm --filter @capybara-hq/mobile apply-brand
import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { type Brand, brand as officialBrand, validateBrand } from "../brand.ts";

const appRoot = fileURLToPath(new URL("..", import.meta.url));

const XCCONFIG = "ios/App/Brand.xcconfig";
const PROPERTIES = "android/brand.properties";
const HASH = "brand-assets.sha256";

const GENERATED = "// Generated by scripts/apply-brand.ts from brand.ts: do not edit.\n";

export function renderXcconfig(b: Brand): string {
  return `${GENERATED}BRAND_NAME = ${b.productName}\nBRAND_APP_ID = ${b.appId}\nBRAND_SCHEME = ${b.scheme}\n`;
}

export function renderProperties(b: Brand): string {
  return `# Generated by scripts/apply-brand.ts from brand.ts: do not edit.\nappName=${b.productName}\napplicationId=${b.appId}\nscheme=${b.scheme}\n`;
}

async function sourceHash(root: string, b: Brand): Promise<string> {
  const hash = createHash("sha256");
  const parts: [string, Buffer | string][] = [
    ["icon", await readFile(`${root}${b.icon}`)],
    ["splash", await readFile(`${root}${b.splash.image}`)],
    ["light", b.splash.background.light.toLowerCase()],
    ["dark", b.splash.background.dark.toLowerCase()],
  ];
  for (const [name, data] of parts) hash.update(`${name}:${data.length}:`).update(data);
  return `${hash.digest("hex")}\n`;
}

async function readOrNull(path: string): Promise<string | null> {
  return readFile(path, "utf8").catch(() => null);
}

const PBXPROJ = "ios/App/App.xcodeproj/project.pbxproj";
const INFO_PLIST = "ios/App/App/Info.plist";
const MANIFEST = "android/app/src/main/AndroidManifest.xml";
const GRADLE = "android/app/build.gradle";

/** The native files that must read the generated values instead of carrying their own copy. */
async function consumptionDrift(root: string, b: Brand): Promise<string[]> {
  const drift: string[] = [];
  const text = async (file: string) => (await readOrNull(`${root}${file}`)) ?? "";
  const literals = (src: string) => src.includes(b.appId) || src.includes(`${b.scheme}://`);

  const pbx = await text(PBXPROJ);
  const ids = [...pbx.matchAll(/PRODUCT_BUNDLE_IDENTIFIER = (.+);/g)].map((m) => m[1] ?? "");
  const appIds = ids.filter((id) => !/\.(AppTests|AppUITests)$/.test(id.replaceAll('"', "")));
  const based = pbx.match(/baseConfigurationReference = \w+ \/\* Brand\.xcconfig \*\//g) ?? [];
  if (
    appIds.length < 2 ||
    appIds.some((id) => id !== '"$(BRAND_APP_ID)"') ||
    based.length < 2 ||
    literals(pbx)
  ) {
    drift.push(PBXPROJ);
  }

  const plist = await text(INFO_PLIST);
  if (
    !/<key>CFBundleDisplayName<\/key>\s*<string>\$\(BRAND_NAME\)<\/string>/.test(plist) ||
    !/<key>CFBundleURLSchemes<\/key>\s*<array>\s*<string>\$\(BRAND_SCHEME\)<\/string>/.test(
      plist,
    ) ||
    literals(plist)
  ) {
    drift.push(INFO_PLIST);
  }

  const manifest = await text(MANIFEST);
  if (!manifest.includes(`android:scheme="\${brandScheme}"`) || literals(manifest)) {
    drift.push(MANIFEST);
  }

  const gradle = await text(GRADLE);
  const needs = [
    'file("../brand.properties")',
    "applicationId brandProperties.getProperty(",
    "brandScheme: brandProperties.getProperty(",
    'resValue "string", "app_name", brandProperties.getProperty(',
  ];
  if (needs.some((n) => !gradle.includes(n)) || literals(gradle)) drift.push(GRADLE);
  return drift;
}

/**
 * Check mode compares the three generated text files with what the brand renders, checks that the
 * native project files read them, and writes nothing; otherwise it writes them and renders the icon and splash sets.
 * `root` and `brand` are for tests; they default to apps/mobile and the official brand.
 */
export async function applyBrand(opts: {
  check: boolean;
  root?: string;
  brand?: Brand;
}): Promise<{ drift: string[] }> {
  const root = opts.root ?? appRoot;
  const b = opts.brand ?? officialBrand;
  const problems = validateBrand(b);
  if (problems.length > 0) throw new Error(`Invalid brand:\n${problems.join("\n")}`);

  const expected: Record<string, string> = {
    [XCCONFIG]: renderXcconfig(b),
    [PROPERTIES]: renderProperties(b),
    [HASH]: await sourceHash(root, b),
  };
  const drift: string[] = [];
  for (const [file, text] of Object.entries(expected)) {
    if ((await readOrNull(`${root}${file}`)) !== text) drift.push(file);
  }
  drift.push(...(await consumptionDrift(root, b)));
  if (opts.check) return { drift };

  for (const [file, text] of Object.entries(expected)) {
    await mkdir(dirname(`${root}${file}`), { recursive: true });
    await writeFile(`${root}${file}`, text);
  }
  renderSets(root, b);
  return { drift };
}

function renderSets(root: string, b: Brand): void {
  // capacitor-assets reformats the manifest as a side effect: keep the hand-written one.
  const manifestPath = `${root}android/app/src/main/AndroidManifest.xml`;
  const manifest = readFileSync(manifestPath, "utf8");
  const bin = fileURLToPath(new URL("../node_modules/.bin/capacitor-assets", import.meta.url));
  const result = spawnSync(
    bin,
    [
      "generate",
      "--ios",
      "--android",
      "--assetPath",
      dirname(b.icon),
      "--iconBackgroundColor",
      b.splash.background.light,
      "--iconBackgroundColorDark",
      b.splash.background.dark,
      "--splashBackgroundColor",
      b.splash.background.light,
      "--splashBackgroundColorDark",
      b.splash.background.dark,
    ],
    { cwd: root, stdio: "inherit" },
  );
  writeFileSync(manifestPath, manifest);
  if (result.status !== 0) throw new Error("capacitor-assets failed");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes("--check");
  const { drift } = await applyBrand({ check });
  if (check && drift.length > 0) {
    console.error(
      `Brand drift in: ${drift.join(", ")}. Run pnpm --filter @capybara-hq/mobile apply-brand.`,
    );
    process.exit(1);
  }
  console.log(check ? "Brand is in sync." : "Brand applied.");
}
